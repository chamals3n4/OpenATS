"use client";

import dynamic from "next/dynamic";
import type { CandidateCvAnalysisPayload } from "@/types";

// Loaded only when the tab is shown: most visits never open it.
const CandidateAiAnalysis = dynamic(
  () => import("../candidate-ai-analysis").then((mod) => ({ default: mod.CandidateAiAnalysis })),
  {
    ssr: false,
    loading: () => (
      <div className="flex flex-col items-center justify-center gap-4 py-16 text-center px-4">
        <p className="text-[13px] text-slate-500 dark:text-neutral-500">
          Loading AI analysis…
        </p>
      </div>
    ),
  },
);

/** Shown only while AI CV analysis is turned on in Settings. */
export function AiAnalysisSection({
  hasResume,
  cvAnalysis,
}: {
  hasResume: boolean;
  cvAnalysis: CandidateCvAnalysisPayload | null;
}) {
  return (
    <div className="p-5 sm:p-6">
      <div className="mb-6">
        <h3 className="text-sm font-bold text-slate-900 dark:text-neutral-100">
          AI analysis
        </h3>
        <p className="text-sm text-slate-500 dark:text-neutral-400 mt-0.5">
          Generated by AI. Not part of the score.
        </p>
      </div>
      <CandidateAiAnalysis hasResume={hasResume} cv={cvAnalysis} />
    </div>
  );
}
